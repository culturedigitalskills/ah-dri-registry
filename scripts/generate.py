#!/usr/bin/env python3
"""Generate the JSON Schemas and the Pages CMS configuration.

Sources:  schema/fields.yml  and  data/vocabularies.yml
Outputs:  schema/<collection>.schema.json  and  .pages.yml

Usage:
    python scripts/generate.py           # write the files
    python scripts/generate.py --check   # fail if the files are out of date
"""
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
FIELDS = ROOT / "schema" / "fields.yml"
VOCABS = ROOT / "data" / "vocabularies.yml"
PAGES = ROOT / ".pages.yml"
SCHEMA_BASE = "https://culturedigitalskills.github.io/ah-dri-registry/api/v1/schema"

ID_PATTERN = r"^[a-z0-9]+(-[a-z0-9]+)*$"
URL_PATTERN = r"^https?://\S+$"
EMAIL_PATTERN = r"^[^@\s]+@[^@\s]+\.[^@\s]+$"
DATE_PATTERN = r"^\d{4}-\d{2}-\d{2}$"


def load():
    fields = yaml.safe_load(FIELDS.read_text(encoding="utf-8"))
    vocabs = yaml.safe_load(VOCABS.read_text(encoding="utf-8"))
    return fields, vocabs


def labels(vocabs, name):
    if name not in vocabs:
        sys.exit(f"Unknown vocabulary '{name}' in schema/fields.yml")
    return [str(v["label"]) for v in vocabs[name]]


def json_schema(coll_name, coll, vocabs):
    props, required = {}, []
    for f in coll["fields"]:
        t = f["type"]
        p = {"title": f["label"]}
        if f.get("description"):
            p["description"] = f["description"]
        if t == "id":
            p.update(type="string", pattern=ID_PATTERN)
        elif t in ("string", "text"):
            p.update(type="string", minLength=1)
        elif t == "url":
            p.update(type="string", pattern=URL_PATTERN)
        elif t == "email":
            p.update(type="string", pattern=EMAIL_PATTERN)
        elif t == "date":
            p.update(type="string", pattern=DATE_PATTERN)
        elif t == "select":
            p.update(type="string", enum=labels(vocabs, f["vocab"]))
        elif t == "reference":
            item = {"type": "string", "pattern": ID_PATTERN}
            if f.get("multiple"):
                p.update(type="array", items=item, uniqueItems=True)
            else:
                p.update(item)
        else:
            sys.exit(f"Unknown field type '{t}' for {coll_name}.{f['key']}")
        if f.get("eosc"):
            p["x-eosc"] = f["eosc"]
        if f.get("core"):
            p["x-core"] = True
        props[f["key"]] = p
        if f.get("required"):
            required.append(f["key"])
    slug = coll_name.replace("_", "-")
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": f"{SCHEMA_BASE}/{slug}.schema.json",
        "title": coll["label"],
        "description": coll.get("description", ""),
        "type": "object",
        "additionalProperties": False,
        "required": required,
        "properties": props,
    }


def pages_field(f, vocabs):
    t = f["type"]
    out = {"name": f["key"], "label": f["label"]}
    if f.get("description"):
        out["description"] = f["description"]
    if t in ("id", "string", "url", "email"):
        out["type"] = "string"
    elif t == "text":
        out["type"] = "text"
    elif t == "date":
        out["type"] = "date"
    elif t == "select":
        out["type"] = "select"
        out["options"] = {"values": labels(vocabs, f["vocab"])}
    elif t == "reference":
        out["type"] = "reference"
        opts = {
            "collection": f["collection"],
            "search": "name,short_name",
            "value": "{id}",
            "label": "{name}",
        }
        if f.get("multiple"):
            opts["multiple"] = True
        out["options"] = opts
    if f.get("required"):
        out["required"] = True
    return out


def pages_config(fields, vocabs):
    content = []
    for coll_name, coll in fields.items():
        content.append({
            "name": coll_name,
            "label": coll["label"],
            "description": coll.get("description", ""),
            "type": "collection",
            "path": coll["folder"],
            "format": "yaml",
            "filename": "{fields.id}.yml",
            "fields": [pages_field(f, vocabs) for f in coll["fields"]],
        })
    return {"settings": {"commit": {"identity": "user"}}, "content": content}


HEADER = (
    "# Pages CMS configuration for the A&H DRI registry.\n"
    "# GENERATED by scripts/generate.py from schema/fields.yml and\n"
    "# data/vocabularies.yml. Do not edit by hand: change those files and\n"
    "# run `python scripts/generate.py`.\n"
)


def render():
    fields, vocabs = load()
    outputs = {}
    for coll_name, coll in fields.items():
        slug = coll_name.replace("_", "-")
        path = ROOT / "schema" / f"{slug}.schema.json"
        outputs[path] = json.dumps(json_schema(coll_name, coll, vocabs), indent=2, ensure_ascii=False) + "\n"
    outputs[PAGES] = HEADER + yaml.safe_dump(
        pages_config(fields, vocabs), sort_keys=False, allow_unicode=True, width=1000
    )
    return outputs


def main():
    check = "--check" in sys.argv
    stale = []
    for path, text in render().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != text:
            if check:
                stale.append(path.relative_to(ROOT))
            else:
                path.write_text(text, encoding="utf-8")
                print(f"wrote {path.relative_to(ROOT)}")
    if check and stale:
        print("These generated files are out of date:")
        for p in stale:
            print(f"  {p}")
        print("Run `python scripts/generate.py` and commit the result.")
        sys.exit(1)
    if check:
        print("Generated files are up to date.")


if __name__ == "__main__":
    main()
